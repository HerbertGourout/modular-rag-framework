class TestMainFailsClosedOnLinuxResolverFailure:
    """Codex review HIGH-003, round 2's own recommended regression: main()
    itself must exit non-zero when the transitive check cannot complete on
    Linux, not just the lower-level function in isolation -- covers the
    full path including how main() aggregates and prints the result."""

    def test_main_exits_nonzero_when_the_linux_resolver_fails(self) -> None:
        with patch("scripts.check_lock_sync.platform.system", return_value="Linux"), patch(
            "scripts.check_lock_sync.subprocess.run",
            return_value=MagicMock(returncode=1, stderr="ResolutionImpossible"),
        ):
            exit_code = main()
        assert exit_code != 0

    def test_main_exits_nonzero_on_a_linux_timeout(self) -> None:
        with patch("scripts.check_lock_sync.platform.system", return_value="Linux"), patch(
            "scripts.check_lock_sync.subprocess.run",
            side_effect=subprocess.TimeoutExpired(cmd="pip", timeout=180),
        ):
            exit_code = main()
        assert exit_code != 0

    def test_main_still_exits_zero_on_non_linux_when_everything_else_passes(self) -> None:
        """The real repo files pass every static check; on a non-Linux host
        the transitive sub-check must skip (not fail), so main() still
        succeeds overall -- this is the legitimate skip case, distinct from
        the two Linux-failure cases above."""
        with patch("scripts.check_lock_sync.platform.system", return_value="Windows"):
            exit_code = main()
        assert exit_code == 0


class TestRunStaticChecksOnRealRepoFiles:
    def test_the_actual_dockerfile_and_lock_pass(self) -> None:
        """Catches checker-assumption drift (a regex that silently stops
        matching the real files' current format) that fixture-only tests
        cannot -- this is the same file the CI gate itself reads. Only the
        static (portable) checks -- transitive resolution is exercised
        separately and is platform-gated."""
        root = Path(__file__).resolve().parents[3]
        dockerfile_text = (root / "Dockerfile").read_text(encoding="utf-8")
        lock_text = (root / "requirements-lock.txt").read_text(encoding="utf-8")
        pyproject_text = (root / "pyproject.toml").read_text(encoding="utf-8")
        pyproject = tomllib.loads(pyproject_text)
        dockerignore_text = (root / ".dockerignore").read_text(encoding="utf-8")

        problems, extras = run_static_checks(
            dockerfile_text, lock_text, pyproject, pyproject_text, dockerignore_text
        )
        assert problems == []
        assert extras == ["v1", "langgraph", "postgres", "auth"]
